public class Ex01 {
    public static void main(String[] args) {

        System.out.println("Primeira maneira\n");

        for (int i = 0; i < 10; i++ ){
            System.out.println(i);
        }

        System.out.println("");
        System.out.println("Segunda maneira\n");

        int i = 1;

        while (i  <= 10){
            System.out.println(i);
            i++;
        }
    }
}